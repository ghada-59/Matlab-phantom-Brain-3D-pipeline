function report = runBatch(varargin)
%RUNBATCH Measure several random ellipsoids and stack the relative errors.
%
%   Each phantom gets its own seed (Seed + index - 1). The default count
%   is 10. The unit test calls the function with a smaller count. The table
%   is written only when OutDir is set. No error value is hard-coded.

    parser = inputParser;
    parser.FunctionName = 'runBatch';
    parser.addParameter('NumPhantoms', 10);
    parser.addParameter('VoxelSpacingMM', [1 1 1]);
    parser.addParameter('NoiseSigmaHU', 0);
    parser.addParameter('Seed', 42);
    parser.addParameter('OutDir', '');
    parser.parse(varargin{:});
    opt = parser.Results;

    count = double(opt.NumPhantoms);
    if ~isscalar(count) || count < 1 || count ~= floor(count)
        error('runBatch:InvalidCount', 'NumPhantoms must be a positive integer.');
    end

    collected = cell(1, count);
    for index = 1:count
        phantom = generateEllipsoidPhantom( ...
            'RandomAxes', true, ...
            'VoxelSpacingMM', opt.VoxelSpacingMM, ...
            'NoiseSigmaHU', opt.NoiseSigmaHU, ...
            'Seed', opt.Seed + index - 1);
        meas = runPipeline(phantom, 'SigmaMM', 0, 'OpenRadiusMM', 0, ...
            'CloseRadiusMM', 0, 'MeshSmoothSigmaVox', 0);
        estimated = sort(meas.semiAxesMM, 'descend');
        truth = sort(phantom.semiAxesMM, 'descend');
        collected{index} = struct( ...
            'index', index, ...
            'seed', opt.Seed + index - 1, ...
            'semiAxisXMM', phantom.semiAxesMM(1), ...
            'semiAxisYMM', phantom.semiAxesMM(2), ...
            'semiAxisZMM', phantom.semiAxesMM(3), ...
            'analyticVolumeMM3', phantom.analyticVolumeMM3, ...
            'voxelVolumeMM3', meas.voxelVolumeMM3, ...
            'meshVolumeMM3', meas.meshVolumeMM3, ...
            'meshAreaMM2', meas.meshAreaMM2, ...
            'relErrVoxelVolume', meas.relErrVoxelVolume, ...
            'relErrMeshVolume', meas.relErrMeshVolume, ...
            'relErrArea', meas.relErrArea, ...
            'estSemiAxis1MM', estimated(1), ...
            'estSemiAxis2MM', estimated(2), ...
            'estSemiAxis3MM', estimated(3), ...
            'relErrAxis1', relativeError(estimated(1), truth(1)), ...
            'relErrAxis2', relativeError(estimated(2), truth(2)), ...
            'relErrAxis3', relativeError(estimated(3), truth(3)), ...
            'sphericityMesh', meas.sphericityMesh);
    end

    report = struct();
    report.rows = [collected{:}];
    report.table = struct2table(report.rows, 'AsArray', true);
    report.csvPath = '';
    if ~isempty(opt.OutDir)
        if ~exist(opt.OutDir, 'dir')
            mkdir(opt.OutDir);
        end
        report.csvPath = fullfile(opt.OutDir, 'batch.csv');
        writetable(report.table, report.csvPath);
    end
end
