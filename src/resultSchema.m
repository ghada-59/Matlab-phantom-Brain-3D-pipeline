function schema = resultSchema()
%RESULTSCHEMA Version and units shared by the MATLAB export and the dashboard.
%   relativeError is dimensionless, so its unit token is '1'.
%   This schema does not contain a measured value.

    schema.version = '1.0';
    schema.sentinel = unmeasuredSentinel();
    schema.units = struct( ...
        'length', 'mm', ...
        'area', 'mm^2', ...
        'volume', 'mm^3', ...
        'intensity', 'HU', ...
        'relativeError', '1');
    schema.requiredWhenExecuted = { ...
        'voxelVolumeMM3', 'meshVolumeMM3', 'meshAreaMM2', ...
        'semiAxesMM', 'sphericityMesh', 'sphericityVoxel'};
end
